func setResourceField(t *testing.T, r *v1.Resource, value any, fields ...string) {
	t.Helper()
	m := r.GetResource().AsMap()
	if err := unstructured.SetNestedField(m, value, fields...); err != nil {
		t.Fatal(err)
	}
	r.Resource = resource.MustStructObject(&unstructured.Unstructured{Object: m})
}

func stableRequest(t *testing.T) *v1.RunFunctionRequest {
	t.Helper()
	r := &v1.RunFunctionRequest{
		Input: resource.MustStructObject(&v1beta1.Input{
			CacheTTL: "1m", StableCacheTTL: "5m",
			EnableDeletionSequencing: true, ReplayDeletion: true,
			UsageVersion: v1beta1.UsageV2, ResetCompositeReadiness: true,
			Rules: []v1beta1.SequencingRule{{Sequence: []resource.Name{"first", "second"}}},
		}),
		Observed: &v1.State{
			Composite: &v1.Resource{Resource: resource.MustStructJSON(`{
				"apiVersion":"example.org/v1","kind":"XR","metadata":{"name":"example","generation":1},
				"status":{"conditions":[{"type":"Ready","status":"True"},{"type":"Synced","status":"True"}]}
			}`)},
			Resources: map[string]*v1.Resource{},
		},
		Desired: &v1.State{
			Composite: &v1.Resource{Resource: resource.MustStructJSON(`{"apiVersion":"example.org/v1","kind":"XR"}`)},
			Resources: map[string]*v1.Resource{},
		},
	}
	for _, name := range []string{"first", "second"} {
		d := &v1.Resource{Ready: v1.Ready_READY_TRUE, Resource: resource.MustStructObject(&unstructured.Unstructured{Object: map[string]any{
			"apiVersion": "example.org/v1", "kind": "Resource",
			"metadata": map[string]any{"name": name}, "spec": map[string]any{"value": "old"},
		}})}
		r.GetDesired().GetResources()[name] = d
		r.GetObserved().GetResources()[name] = proto.Clone(d).(*v1.Resource)
		setResourceField(t, r.GetObserved().GetResources()[name], map[string]any{"conditions": []any{
			map[string]any{"type": "Ready", "status": "True", "observedGeneration": int64(1)},
			map[string]any{"type": "Synced", "status": "True", "observedGeneration": int64(1)},
		}}, "status")
		setResourceField(t, r.GetObserved().GetResources()[name], int64(1), "metadata", "generation")
	}
	// A stable graph includes the Usage generated by an earlier reconcile.
	f := &Function{log: logging.NewNopLogger()}
	rsp, err := f.RunFunction(context.Background(), r)
	if err != nil {
		t.Fatal(err)
	}
	u := rsp.GetDesired().GetResources()["second-first-usage"]
	if u == nil {
		t.Fatal("expected deletion dependency to be generated")
	}
	r.GetObserved().GetResources()["second-first-usage"] = proto.Clone(u).(*v1.Resource)
	return r
}

func TestStableCacheTTLLifecycle(t *testing.T) {
	cases := map[string]struct {
		change func(*testing.T, *v1.RunFunctionRequest)
		want   time.Duration
	}{
		"Stable": {want: 5 * time.Minute},
		"LaterPipelineResource": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			r.GetObserved().GetResources()["later"] = &v1.Resource{Resource: resource.MustStructJSON(`{"apiVersion":"v1","kind":"ConfigMap","metadata":{"name":"later"}}`)}
		}, want: 5 * time.Minute},
		"LaterDeletionProtection": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			r.GetObserved().GetResources()["protection"] = proto.Clone(r.GetObserved().GetResources()["second-first-usage"]).(*v1.Resource)
		}, want: 5 * time.Minute},
		"CustomActiveTTL": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			r.GetInput().GetFields()["cacheTTL"] = structpb.NewStringValue("30s")
			delete(r.GetObserved().GetResources(), "second")
		}, want: 30 * time.Second},
		"Disabled": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			delete(r.GetInput().GetFields(), "stableCacheTTL")
		}, want: time.Minute},
		"MissingChild": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			delete(r.GetObserved().GetResources(), "second")
		}, want: time.Minute},
		"NewUsage": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			delete(r.GetObserved().GetResources(), "second-first-usage")
		}, want: time.Minute},
		"BlockedCreation": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			delete(r.GetObserved().GetResources(), "second")
			r.GetDesired().GetResources()["first"].Ready = v1.Ready_READY_FALSE
		}, want: time.Minute},
		"DeletingComposite": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetObserved().GetComposite(), "2026-01-01T00:00:00Z", "metadata", "deletionTimestamp")
		}, want: time.Minute},
		"DeletingChild": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetObserved().GetResources()["second"], "2026-01-01T00:00:00Z", "metadata", "deletionTimestamp")
		}, want: time.Minute},
		"RemovedFromDesired": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			delete(r.GetDesired().GetResources(), "second")
		}, want: time.Minute},
		"CompositeNotReady": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetObserved().GetComposite(), []any{map[string]any{"type": "Ready", "status": "False"}}, "status", "conditions")
		}, want: time.Minute},
		"DesiredCompositeNotReady": {change: func(_ *testing.T, r *v1.RunFunctionRequest) {
			r.GetDesired().GetComposite().Ready = v1.Ready_READY_FALSE
		}, want: time.Minute},
		"ChildNotSynced": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetObserved().GetResources()["first"], []any{map[string]any{"type": "Synced", "status": "False"}}, "status", "conditions")
		}, want: time.Minute},
		"ChildNotReadyDespiteOverride": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetObserved().GetResources()["first"], []any{map[string]any{"type": "Ready", "status": "False"}}, "status", "conditions")
		}, want: time.Minute},
		"StaleConditions": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetObserved().GetResources()["first"], int64(2), "metadata", "generation")
		}, want: time.Minute},
		"DesiredUpdate": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetDesired().GetResources()["first"], "new", "spec", "value")
		}, want: time.Minute},
		"ObservedDrift": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetObserved().GetResources()["first"], "drifted", "spec", "value")
		}, want: time.Minute},
		"APIDefaults": {change: func(t *testing.T, r *v1.RunFunctionRequest) {
			t.Helper()
			setResourceField(t, r.GetObserved().GetResources()["first"], "default", "spec", "defaulted")
		}, want: 5 * time.Minute},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			r := stableRequest(t)
			if tc.change != nil {
				tc.change(t, r)
			}
			baseline := proto.Clone(r).(*v1.RunFunctionRequest)
			delete(baseline.GetInput().GetFields(), "stableCacheTTL")
			f := &Function{log: logging.NewNopLogger()}
			want, err := f.RunFunction(context.Background(), baseline)
			if err != nil {
				t.Fatal(err)
			}
			got, err := f.RunFunction(context.Background(), r)
			if err != nil {
				t.Fatal(err)
			}
			if got.GetMeta().GetTtl().AsDuration() != tc.want {
				t.Errorf("TTL = %s, want %s", got.GetMeta().GetTtl().AsDuration(), tc.want)
			}
			// Readiness, creation filtering, and deletion edges must be identical.
			want.Meta.Ttl = got.GetMeta().GetTtl()
			if diff := cmp.Diff(want, got, protocmp.Transform()); diff != "" {
				t.Errorf("sequencing changed beyond its TTL (-want +got):\n%s", diff)
			}
		})
	}
}

func TestStableCacheTTLValidation(t *testing.T) {
	for _, ttl := range []string{"invalid", "0s", "-1s", "30s", "1m"} {
		t.Run(ttl, func(t *testing.T) {
			r := stableRequest(t)
			r.GetInput().GetFields()["stableCacheTTL"] = structpb.NewStringValue(ttl)
			f := &Function{log: logging.NewNopLogger()}
			got, err := f.RunFunction(context.Background(), r)
			if err != nil {
				t.Fatal(err)
			}
			if len(got.GetResults()) != 1 || got.GetResults()[0].GetSeverity() != v1.Severity_SEVERITY_FATAL {
				t.Fatalf("expected invalid stableCacheTTL to fail, got %v", got.GetResults())
			}
		})
	}
}

func TestDesiredFieldsMatch(t *testing.T) {
	cases := []struct {
		name              string
		desired, observed any
		want              bool
	}{
		{"Defaults", map[string]any{"a": "x"}, map[string]any{"a": "x", "b": "y"}, true},
		{"Missing", map[string]any{"a": nil}, map[string]any{}, false},
		{"ClearString", "", "x", false},
		{"ClearBoolean", false, true, false},
		{"ClearNumber", int64(0), int64(1), false},
		{"Lists", []any{map[string]any{"a": "x"}}, []any{map[string]any{"a": "x", "b": "y"}}, true},
		{"ShorterList", []any{}, []any{"x"}, false},
		{"ReorderedList", []any{"x", "y"}, []any{"y", "x"}, false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := desiredFieldsMatch(tc.desired, tc.observed); got != tc.want {
				t.Errorf("desiredFieldsMatch() = %v, want %v", got, tc.want)
			}
		})
	}
}
